String errorKey(Object error) {
  // UI translates status classes; raw server diagnostics remain in the API layer.
  if (error is! ApiException) return 'genericError';
  return switch (error.status) {
    0 => 'offline',
    401 => 'expired',
    403 => 'forbidden',
    404 => 'notFound',
    409 => 'conflict',
    419 => 'securityExpired',
    422 => 'validation',
    429 => 'rateLimit',
    _ => 'serverError',
  };
}
