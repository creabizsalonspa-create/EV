// Local primary-platform proof; never sends hardware or payment commands.
const { BusinessClient } = require('./helpers/business-client.cjs');
const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const assert = require('node:assert/strict');
(async () => {
 const root = path.resolve('artifacts/client-demo');
 const file = fs.realpathSync(process.env.EV_CLIENT_DEMO_MANIFEST || JSON.parse(fs.readFileSync(path.join(root,'current.json'))).manifest);
 assert(file.startsWith(root + path.sep) && (fs.statSync(file).mode & 0o077) === 0);
 const fixture = JSON.parse(fs.readFileSync(file));
 assert(fixture.fixture_only && !fixture.real_money);
 const client = new BusinessClient();
 client.csrf = (await client.request('csrf')).token;
 await client.request('login','POST',fixture.accounts.customer);
 client.csrf = (await client.request('csrf')).token;
 let vehicle = (await client.request('vehicles')).data[0];
 if (!vehicle) vehicle = await client.request('vehicles','POST',{name:'Demo EV','connector_type':'CCS2'});
 assert(vehicle.can_simulate_battery !== false);
 const body = {operation_key:randomUUID(),battery_percent:15};
 const first = await client.request(`vehicles/${vehicle.id}/battery-simulation`,'POST',body);
 const replay = await client.request(`vehicles/${vehicle.id}/battery-simulation`,'POST',body);
 assert.equal(first.notification_id,replay.notification_id);
 const notification = (await client.request('notifications')).data.find(x=>x.id===first.notification_id);
 assert.equal(notification.kind,'vehicle.battery.simulated');
 assert.equal(notification.metadata.source,'simulator');
 const browser = await chromium.launch({headless:true,executablePath:process.env.EV_CHROMIUM_PATH || '/usr/bin/chromium',args:['--no-sandbox']});
 try {
  const context = await browser.newContext();
  await context.addCookies([...client.cookies].map(([name,value])=>({name,value,url:client.base})));
  const page = await context.newPage();
  const ready = page.waitForResponse(r=>new URL(r.url()).pathname==='/api/notifications' && r.request().method()==='GET');
  await page.goto(client.base);
  await ready;
  await page.waitForFunction(()=>user?.role==='customer');
  assert.equal(await page.locator('#vehicle-list button').count()>0,true);
  assert.match(await page.locator('#notifications').innerText(),/Simulated low battery/);
  const row = page.locator('#vehicle-list > div').filter({hasText: '#' + vehicle.id + ' ·'});
  await row.getByRole('button', {name:'Battery preferences',exact:true}).click();
  const editor = row.locator('[data-battery-editor]');
  const simulated = editor.getByLabel('Simulated battery % (0–100)');
  await simulated.fill('');
  const accidental = [];
  const watch = r => {if (r.url().endsWith('/battery-simulation') && r.method()==='POST') accidental.push(r);};
  page.on('request',watch);
  await editor.getByRole('button',{name:'Record simulator observation',exact:true}).click();
  assert.equal(await simulated.evaluate(e=>e.validity.valueMissing),true);
  assert.equal(accidental.length,0);
  page.off('request',watch);
  await simulated.fill('15');

  await editor.getByLabel('Threshold % (1–50)').fill('10');
  let saved = page.waitForResponse(r=>r.url().endsWith(`/vehicles/${vehicle.id}/battery-preferences`) && r.request().method()==='PUT');
  await editor.getByRole('button',{name:'Save battery preferences',exact:true}).click();
  assert.equal((await saved).status(),200);
  await editor.getByRole('button',{name:'Record simulator observation',exact:true}).click();
  await editor.getByText('Simulator observation saved; preferences did not trigger an alert.',{exact:true}).waitFor();
  await editor.getByLabel('Threshold % (1–50)').fill('20');
  saved = page.waitForResponse(r=>r.url().endsWith(`/vehicles/${vehicle.id}/battery-preferences`) && r.request().method()==='PUT');
  await editor.getByRole('button',{name:'Save battery preferences',exact:true}).click();
  assert.equal((await saved).status(),200);
  await editor.getByRole('button',{name:'Record simulator observation',exact:true}).click();
  await editor.getByText('Simulated alert saved in Notifications.',{exact:true}).waitFor();
  await page.evaluate(()=>support());
  const alert = page.locator('#notifications > p').filter({hasText:'Vehicle ' + vehicle.id + ' ·'}).first();
  await alert.getByRole('button',{name:'Find compatible chargers',exact:true}).click();
  await page.waitForFunction(()=>location.hash==='#discover');
  assert.equal(await page.locator('#filters [name=connector_type]').inputValue(),vehicle.connector_type);
  const compatible = (await client.request('stations?connector_type=' + vehicle.connector_type)).data;
  const position = compatible.find(s=>s.latitude!==null && s.longitude!==null);
  assert(position, 'A catalog map point is required for nearby discovery proof');
  await page.locator('#filters details').evaluate(e=>e.open=true);
  await page.locator('#filters [name=latitude]').fill(String(position.latitude));
  await page.locator('#filters [name=longitude]').fill(String(position.longitude));
  await page.locator('#filters [name=radius_km]').fill('10');
  const nearby = page.waitForResponse(r=>new URL(r.url()).pathname==='/api/stations' && new URL(r.url()).searchParams.get('radius_km')==='10');
  await page.locator('#filters').getByRole('button',{name:/Search/}).click();
  const response = await nearby;
  assert.equal(response.status(),200);
  assert((await response.json()).data.length>0);
  await page.locator('#language').click();
  await editor.getByLabel('عتبة التنبيه ٪ (1–50)').waitFor();
  assert.match(await page.locator('#notifications').innerText(), /محاكاة بطارية منخفضة/);
  assert.equal(await editor.getByLabel('عتبة التنبيه ٪ (1–50)').inputValue(), '20');
  assert.equal(await editor.getByRole('button',{name:'حفظ تفضيلات البطارية',exact:true}).count(),1);
  assert.equal(await editor.getByRole('button',{name:'البحث عن شواحن متوافقة',exact:true}).count(),1);


  await context.close();
 } finally {await browser.close();}
 console.log('Persisted preferences -> threshold-aware simulator alert -> inbox -> compatible catalog -> explicit nearby search passed; no charging/payment mutation.');
})().catch(e=>{console.error(e.message);process.exitCode=1;});
